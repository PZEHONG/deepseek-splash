const { app, BrowserWindow, screen } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const stage = name => fs.appendFileSync(path.join(root, 'review', 'test-stages.log'), name + '\n');
stage('entry');
const profile = path.join(root, 'temp', 'preview-profile');
fs.mkdirSync(profile, { recursive: true });
for (const key of ['userData', 'sessionData', 'appData', 'temp']) app.setPath(key, profile);
app.setAppLogsPath(path.join(profile, 'logs'));
app.disableHardwareAcceleration();
app.on('window-all-closed', () => {});
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  stage('app-ready');
  setTimeout(() => { stage('watchdog-expired'); app.exit(2); }, 14000);
  const packaged = process.env.HARNESS_ARCHIVE_CHECK === '1';
  const { createHarnessSplash } = await import(packaged ? '../delivery/app.asar/lib/harness-splash.mjs' : '../package/harness-splash.mjs');
  stage('module-loaded');
  const assets = packaged ? path.join(root, 'delivery', 'app.asar', 'renderer') : path.join(root, 'package');
  const splash = createHarnessSplash({ BrowserWindow, assetDirectory: assets });
  stage('window-created');
  const created = BrowserWindow.getAllWindows()[0];
  created.webContents.on('did-fail-load', (_event, code, description) => stage('load-failed: ' + code + ' ' + description));
  created.webContents.on('console-message', details => stage('console: ' + details.message));
  created.once('ready-to-show', () => stage('ready-to-show: ' + created.isVisible()));
  await Promise.race([new Promise(resolve => created.webContents.once('did-finish-load', resolve)), delay(6000)]);
  stage('loaded: ' + created.webContents.getURL());
  // Start-Process -WindowStyle Hidden suppresses Windows' first ShowWindow call.
  created.show();
  await delay(2300);
  stage('capture-start');
  const window = BrowserWindow.getAllWindows()[0];
  assert(window && window.isVisible(), 'Splash must be visible while the video plays');
  const display = screen.getDisplayMatching(window.getBounds());
  const captured = await window.webContents.capturePage();
  const geometry = { window: window.getBounds(), content: window.getContentBounds(), display: display.bounds, workArea: display.workArea, scaleFactor: display.scaleFactor, capture: captured.getSize(), fullscreenFlag: window.isFullScreen(), displays: screen.getAllDisplays().map(({id,bounds,scaleFactor})=>({id,bounds,scaleFactor})) };
  fs.writeFileSync(path.join(root, 'review', 'display-diagnostic.json'), JSON.stringify(geometry, null, 2));
  assert.equal(window.isFullScreen(), false, 'The intro must use its initial ordinary window size');
  assert.equal(window.isMaximized(), false);
  assert.equal(window.getContentBounds().width, Math.min(960, display.workArea.width));
  assert.equal(window.getContentBounds().height, Math.min(540, display.workArea.height));
  assert(Math.abs(window.getBounds().x + window.getBounds().width / 2 - display.workArea.x - display.workArea.width / 2) <= 1, 'The intro must be centered horizontally');
  assert(Math.abs(window.getBounds().y + window.getBounds().height / 2 - display.workArea.y - display.workArea.height / 2) <= 1, 'The intro must be centered vertically');
  const video = await window.webContents.executeJavaScript(`(()=>{const v=document.querySelector('video');const q=v.getVideoPlaybackQuality();return {time:v.currentTime,width:v.videoWidth,height:v.videoHeight,muted:v.muted,title:document.querySelector('h1').textContent,playing:!v.paused,totalFrames:q.totalVideoFrames,droppedFrames:q.droppedVideoFrames,fit:getComputedStyle(v).objectFit};})()`);
  assert(video.time > 0.5 && video.playing, 'Video must autoplay');
  assert.equal(video.width, 3840, 'The decoder must receive the original 4K video');
  assert.equal(video.height, 2160);
  assert.equal(video.fit, 'cover');
  assert.equal(video.muted, true);
  assert.equal(video.title, 'DeepSeek Harness');
  fs.writeFileSync(path.join(root, 'review', 'splash-preview.png'), (await window.webContents.capturePage()).toPNG());
  const before = Date.now();
  await splash.finish();
  assert(Date.now() - before < 180, 'A ready application must stop the animation immediately, without waiting for the video');
  assert(window.isDestroyed(), 'Splash must close after the application is ready');
  const synchronized = createHarnessSplash({ BrowserWindow, assetDirectory: assets });
  const appWindow = new BrowserWindow({ show: false, width: 1280, height: 820, webPreferences: { sandbox: true } });
  const initialApplicationBounds = appWindow.getBounds();
  synchronized.hold(appWindow);
  await appWindow.loadURL('data:text/html,<main>Application ready</main>');
  appWindow.show();
  assert.equal(appWindow.isVisible(), false, 'The application must remain hidden behind the intro until the UI is ready');
  await delay(450);
  assert.equal(appWindow.isVisible(), false, 'Completing backend startup must not expose the built-in loading screen');
  const readyAt = Date.now();
  synchronized.workspaceReady(appWindow);
  await synchronized.closed;
  assert(Date.now() - readyAt < 180, 'UI readiness must reveal the app immediately');
  assert.equal(appWindow.isVisible(), true);
  assert.equal(appWindow.isFullScreen(), false, 'The application must use a regular window');
  assert.equal(appWindow.isMaximized(), false, 'The application must retain its initial ordinary window size');
  assert.deepEqual(appWindow.getBounds(), initialApplicationBounds);
  appWindow.maximize();
  await delay(180);
  assert.equal(appWindow.isMaximized(), true, 'Manual maximize must remain available');
  appWindow.unmaximize();
  await delay(180);
  assert.equal(appWindow.isMaximized(), false, 'Restore must return to a normal window');
  assert.equal(BrowserWindow.getAllWindows().length, 1, 'No video window may remain after the app is shown');
  appWindow.destroy();
  const skip = createHarnessSplash({ BrowserWindow, assetDirectory: assets });
  await delay(650);
  const skipWindow = BrowserWindow.getAllWindows()[0];
  skipWindow.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' });
  await skip.finish();
  assert(skipWindow.isDestroyed(), 'Escape must skip the animation');
  const missing = createHarnessSplash({ BrowserWindow, assetDirectory: path.join(root, 'missing-assets') });
  await Promise.race([missing.finish(), delay(2500).then(() => { throw Error('Missing media blocked startup'); })]);
  fs.writeFileSync(path.join(root, 'review', 'test-result.json'), JSON.stringify({ ok: true, geometry, initialApplicationBounds, video, checks: ['intro-initial-960x540-centered', 'application-original-window-size', 'manual-maximize-and-restore', 'autoplay', 'silent', '3840x2160-4K', 'branding', 'immediate-stop-on-ready', 'main-hidden-until-ui-ready', 'no-video-overlap', 'escape-skip', 'missing-assets-fail-open'] }, null, 2));
  app.exit(0);
}).catch(error => {
  fs.writeFileSync(path.join(root, 'review', 'test-result.json'), JSON.stringify({ ok: false, error: error.stack }, null, 2));
  app.exit(1);
});
